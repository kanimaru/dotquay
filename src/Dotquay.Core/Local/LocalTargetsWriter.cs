using System.Xml.Linq;
using Dotquay.Core.Abstractions;
using Dotquay.Core.Dotnet;

namespace Dotquay.Core.Local;

/// <summary>
/// Generates <c>dotquay.local.targets</c> — the per-machine MSBuild overlay that swaps a linked
/// package's <c>PackageReference</c> for a <c>ProjectReference</c>
/// (docs/DESIGN-v0.11-LOCAL-DOTNET-LINK.md) — and installs the one-line hook that picks it up.
/// </summary>
/// <remarks>
/// <para>
/// <strong>Why an overlay and not an edit.</strong> The consuming <c>.csproj</c> is committed. A
/// <c>ProjectReference</c> to <c>F:\…\generator.csproj</c> written into it is a machine-local absolute
/// path in a tracked file — the exact failure <c>dotquay.local.toml</c> is gitignored to prevent.
/// With the overlay the <c>.csproj</c> keeps its <c>PackageReference</c> verbatim and unlinking is
/// just deleting a file, so there is no path by which a link can be committed.
/// </para>
/// <para>
/// <strong>Why <c>.targets</c> and not <c>.props</c>.</strong> MSBuild evaluates a project in order,
/// and <c>&lt;PackageReference Remove="…"/&gt;</c> deletes an item from the list <em>as it exists at
/// that point</em>. Removing something not yet declared is a legal, silent no-op. Imported early —
/// which is what <c>Directory.Build.props</c> is — the removal would do nothing, the
/// <c>ProjectReference</c> would sit beside a live <c>PackageReference</c>, and the build would go on
/// quietly using the published package. No error, no warning, wrong answer. This is this design's
/// counterpart to the addon link's "never follow a directory link when deleting" rule, and
/// <c>LocalTargetsTests</c> pins the ordering so it fails loudly if the hook ever moves.
/// </para>
/// <para>
/// <strong>Why an own-named file.</strong> MSBuild imports only the <em>first</em>
/// <c>Directory.Build.targets</c> it finds walking up the tree and then stops, so generating one could
/// silently shadow a parent the repository already relies on. A dotquay-named file collides with
/// nothing and is greppable.
/// </para>
/// </remarks>
public static class LocalTargetsWriter
{
    public const string FileName = "dotquay.local.targets";

    private const string HookComment =
        " dotquay: per-machine local .NET links. Inert unless dotquay.local.targets exists, so this line is safe to commit. ";

    /// <summary>
    /// Brings the overlay in line with <paramref name="links"/>: written whole when there is anything
    /// to say, deleted when there is not.
    /// </summary>
    /// <remarks>
    /// Regenerated wholesale rather than edited, because dotquay is the only writer of this file —
    /// which is also why none of v0.10's "did dotquay write this, or did the user" bookkeeping is
    /// needed here.
    /// </remarks>
    public static void Sync(
        IFileSystem fileSystem, string projectDirectory, IReadOnlyDictionary<string, DotnetLink> links)
    {
        var path = fileSystem.CombinePath(projectDirectory, FileName);

        if (links.Count == 0)
        {
            fileSystem.DeleteFile(path);

            // The hook stays. It is inert without this file (Condition="Exists(…)"), and removing it
            // would churn a committed file on every link/unlink cycle — including for teammates, who
            // would see a tracked line appear and disappear for a reason that exists only on one
            // machine.
            return;
        }

        fileSystem.WriteAllText(path, Render(links));
        EnsureHook(fileSystem, projectDirectory);
    }

    private static string Render(IReadOnlyDictionary<string, DotnetLink> links)
    {
        var itemGroup = new XElement("ItemGroup");

        foreach (var link in links.Values.OrderBy(l => l.PackageId, StringComparer.Ordinal))
        {
            // Order matters for readability only — MSBuild applies both regardless — but keeping the
            // Remove beside its ProjectReference makes the swap obvious to anyone who opens the file.
            itemGroup.Add(new XElement("PackageReference", new XAttribute("Remove", link.PackageId)));

            var reference = new XElement(
                "ProjectReference", new XAttribute("Include", link.ProjectPath));

            if (link.Analyzer)
            {
                reference.Add(new XAttribute("OutputItemType", "Analyzer"));
                reference.Add(new XAttribute("ReferenceOutputAssembly", "false"));
            }

            itemGroup.Add(reference);
        }

        var project = new XElement("Project", itemGroup);
        var document = new XDocument(
            new XComment(
                $" Generated by dotquay from {LocalLinks.FileName}. Per-machine — do not commit."
                + $"{Environment.NewLine}     Edits here are overwritten on the next 'dotquay link'. "),
            project);

        return document.ToString(SaveOptions.None) + Environment.NewLine;
    }

    /// <summary>
    /// Adds the conditional <c>&lt;Import&gt;</c> to the consuming <c>.csproj</c> if it isn't already
    /// there, as the <em>last</em> element of <c>&lt;Project&gt;</c>.
    /// </summary>
    /// <remarks>
    /// The only permanent change this feature makes to a tracked file, which is why it is idempotent
    /// and why it is one line. Position is not cosmetic: see the class remarks.
    /// </remarks>
    public static void EnsureHook(IFileSystem fileSystem, string projectDirectory)
    {
        string csprojPath;
        try
        {
            csprojPath = CsprojLocator.Locate(fileSystem, projectDirectory);
        }
        catch (DotnetSyncException ex)
        {
            // Linking a NuGet package in a project with no C# project file is a coherent thing to
            // ask for and an impossible thing to do; say which it is rather than surfacing a
            // PackageReference-flavoured message from a link command.
            throw new LocalLinkException(
                $"A local .NET link needs a project to import the overlay into. {ex.Message}", ex);
        }

        XDocument document;
        try
        {
            document = XDocument.Parse(fileSystem.ReadAllText(csprojPath));
        }
        catch (System.Xml.XmlException ex)
        {
            throw new LocalLinkException($"{csprojPath}: not valid XML.{Environment.NewLine}{ex.Message}", ex);
        }

        var project = document.Root;
        if (project is null || project.Name.LocalName != "Project")
        {
            throw new LocalLinkException($"{csprojPath}: expected a <Project> root element.");
        }

        if (HasHook(project))
        {
            return;
        }

        project.Add(new XComment(HookComment));
        project.Add(new XElement(
            "Import",
            new XAttribute("Project", FileName),
            new XAttribute("Condition", $"Exists('{FileName}')")));

        fileSystem.WriteAllText(csprojPath, document.ToString(SaveOptions.None) + Environment.NewLine);
    }

    /// <summary>Whether the project already imports the overlay, however the line was written.</summary>
    public static bool HasHook(XElement project) =>
        project.Descendants("Import").Any(i =>
            string.Equals((string?)i.Attribute("Project"), FileName, StringComparison.OrdinalIgnoreCase));

    /// <summary>Whether the project at <paramref name="projectDirectory"/> imports the overlay. Used by
    /// <c>doctor</c> to catch the overlay-without-hook case, which is a link that silently does
    /// nothing.</summary>
    public static bool HasHook(IFileSystem fileSystem, string csprojPath)
    {
        try
        {
            var root = XDocument.Parse(fileSystem.ReadAllText(csprojPath)).Root;
            return root is not null && HasHook(root);
        }
        catch (System.Xml.XmlException)
        {
            return false;
        }
    }
}
